-- 动作字典表:英文别名 / 中文显示英文 / 中文变体
-- 自 2026-08-18 起替代 exerciseLib.ts 的 EXERCISE_ALIASES / EXERCISE_EN / EXERCISE_ZH_ALIASES 常量,
-- DB 为唯一真相:App 内 /fit/exercises 独立编辑入口直接读写,改映射不再需要改代码 + 迁移。
create table if not exists public.exercise_dictionary (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('alias', 'en', 'zh_alias')),
  key text not null,
  value text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kind, key)
);

comment on table public.exercise_dictionary is '全局力量动作映射字典(alias=英文别名→中文规范名 / en=非预设规范名→显示英文 / zh_alias=中文变体→中文规范名)';
comment on column public.exercise_dictionary.kind is '条目类型:alias | en | zh_alias';
comment on column public.exercise_dictionary."key" is '键(alias 为小写英文别名;en/zh_alias 为中文名)';
comment on column public.exercise_dictionary.value is '值(中文规范名 / 显示英文名)';

alter table public.exercise_dictionary enable row level security;

